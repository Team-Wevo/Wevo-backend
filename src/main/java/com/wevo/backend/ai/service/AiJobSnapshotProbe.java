package com.wevo.backend.ai.service;

/**
 * 완료 처리 트랜잭션 <b>안에서</b> 현재 입력 스냅샷 해시를 다시 계산하는 콜백.
 *
 * <p>오래된 결과 폐기 판정(§3.8 입력 스냅샷 바인딩)이 실제로 성립하려면, "현재 입력을 읽는 시점"과
 * "결과를 저장하는 시점"이 <b>같은 트랜잭션·같은 잠금 범위</b>여야 한다. 완료 처리 밖에서 미리 계산한
 * 해시를 넘기면 계산과 저장 사이에 입력이 커밋될 수 있어, 대조는 통과했는데 저장된 결과는 이미 낡은
 * 입력 기준이 된다(AiJob 행 잠금은 의견·답변 테이블을 막지 못한다).
 *
 * <p>구현은 해시를 계산하기 전에 <b>입력을 바꾸는 쓰기 경로와 직렬화되는 잠금</b>을 먼저 획득해야 한다.
 * 의견 임시저장·제출·수집 마감/재오픈이 모두 섹션 행을 배타 잠금하므로, 정리 작업은 섹션 행 잠금으로
 * 같은 직렬화 지점에 참여한다.
 */
@FunctionalInterface
public interface AiJobSnapshotProbe {

    /** 잠금을 획득한 뒤 현재 입력으로 계산한 64자리 소문자 SHA-256 hex를 반환한다. */
    String currentSnapshotHash();
}
